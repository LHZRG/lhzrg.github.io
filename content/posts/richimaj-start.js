    "#### 表宝牌、杠宝牌、里宝牌与赤宝牌",
    "",
    "- **表宝牌：**由初始翻开的表指示牌确定，所有合法和牌者均可计算。",
    "- **杠宝牌：**合法杠后增加的表指示牌所确定的宝牌；翻开时点依规则约定。",
    "- **里宝牌：**立直且和牌后，揭开已启用表指示牌正下方的里指示牌，按相同循环确定；只供立直和牌者计算。对应杠指示牌的里宝牌是否采用，依规则约定。",
