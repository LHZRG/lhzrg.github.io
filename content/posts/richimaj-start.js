    "- 每取走1张岭上牌，就把活牌山末端1张划入王牌，使王牌始终保留14张；可理解为边界移动，不是另加一张牌。",
    "",
    "#### 指示牌不等于宝牌",
    "",
    "王牌中初始另有5墩、10张作为**宝牌指示牌的位置**：上层是表指示牌，下层是与之对应的里指示牌。",
    "",
    "开局翻开紧邻岭上区的第1张上层指示牌，之后有合法杠时按约定顺序增加指示牌，最多使用5组。下层的牌并不是「上层指示牌所指向的宝牌」，而是另外一张尚未揭示的指示牌。",
    "",
