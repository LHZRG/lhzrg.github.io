    "| 指示牌类别 | 循环顺序 | 示例 |",
    "| --- | --- | --- |",
    "| 数牌 | 同花色1→2→…→8→9→1 | 指示牌4万，则5万是宝牌；9筒指示1筒 |",
    "| 风牌 | 东→南→西→北→东 | 指示牌北，则东是宝牌 |",
    "| 三元牌 | 白→发→中→白 | 指示牌中，则白是宝牌 |",
    "",
    "指示牌 → 实际宝牌：",
    "[mj 4m] → [mj 5m]；[mj 9p] → [mj 1p]",
    "[mj 4z] → [mj 1z]；[mj 7z] → [mj 5z]",
